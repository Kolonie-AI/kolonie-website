#!/usr/bin/env node
/**
 * One social-preview card per repository in the organisation
 * (kolonie-website#90).
 *
 *     node scripts/build-repo-cards.mjs            # from the committed drawings
 *     node scripts/build-repo-cards.mjs --list     # what the organisation holds
 *
 * A link to any Kolonie repository renders GitHub's grey generated card. The
 * image that would replace it, `og.png`, is the wrong one for the job: it
 * carries a headline, a two-line pitch and a list of three domains — the copy
 * that changes most often, on the surface that is hardest to change, fourteen
 * times over. **Decided by the maintainer on 2026-08-08:** the repository cards
 * lose the claim; the website's own `og.png` keeps it, because a shared link to
 * `kolonie.ai` should say what the Colony is and that file is regenerated on
 * every build. A repository card is uploaded by hand into somebody's settings
 * page and will sit there for a year.
 *
 * ## The split that makes *no text in a generated image* true here
 *
 * `kolonie-website#65` forbids text inside a generated image — it cannot be
 * translated or read aloud. These cards carry words, and the rule still holds,
 * because two different things make them:
 *
 * 1. **The drawing** comes from an image model, carries no text at all, and is
 *    checked against the tokens by `check-illustration-palette.mjs` **before**
 *    it is composited. It is committed under `assets/repo-card-drawings/`.
 * 2. **The card** is assembled here, from an HTML document and a Playwright
 *    screenshot, the way `build-assets.mjs` already builds `og.png`. The lockup
 *    and the names are real type in that document, so they are sharp at any
 *    scale and correct by construction rather than by prompt.
 *
 * ## Why the drawings are committed rather than generated by this script
 *
 * `#90`: *"Regenerating produces the same cards from the same inputs — a reader
 * who runs the generator gets what is committed."* An image model is not a
 * function; asking it twice gives two drawings. So the drawings **are** the
 * inputs, they are in the repository, and this script is deterministic over
 * them. `scripts/snap-illustration-palette.mjs` is what turns a fresh candidate
 * into one of those inputs, and its own comment says why that step exists.
 *
 * ## The repository list is read, not typed
 *
 * `--list` asks GitHub for every public unarchived repository in the
 * organisation and prints the ones this script has no brief for. That is the
 * check `#90` asks for — *a repository added tomorrow is a missing card the
 * build names* — and it needs a token, so it is a command rather than part of
 * the build. `src/lib/repo-cards.built-test.ts` holds the other half: the cards
 * and the briefs must agree, on every build, with no network at all.
 */

import { execFileSync } from 'node:child_process'
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { CARDS, FELL_BACK } from './repo-card-briefs.mjs'
import { TOKENS } from './lib/palette.mjs'

const root = new URL('../', import.meta.url)
const at = (p) => fileURLToPath(new URL(p, root))

const hex = ([r, g, b]) =>
  '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('')

const k = {
  bg: hex(TOKENS['--k-bg']),
  accent: hex(TOKENS['--k-accent']),
  text: '#f1f3f3',
  faint: '#8b9498',
}

/* ---- --list: what the organisation holds, against what this knows ---------- */

if (process.argv.includes('--list')) {
  const query =
    '{organization(login:"Kolonie-AI"){repositories(first:100, privacy:PUBLIC, ' +
    'isArchived:false, ownerAffiliations:OWNER){nodes{name}}}}'
  const answer = execFileSync(
    'gh',
    ['api', 'graphql', '-f', `query=${query}`, '--jq', '.data.organization.repositories.nodes[].name'],
    { encoding: 'utf8' },
  )
  const live = answer.trim().split('\n').filter(Boolean).sort()
  const known = Object.keys(CARDS).sort()

  const missing = live.filter((name) => !known.includes(name))
  const stale = known.filter((name) => !live.includes(name))

  console.log(`${live.length} public unarchived repositories, ${known.length} briefs`)
  for (const name of missing) console.log(`  no card:  ${name}`)
  for (const name of stale) console.log(`  no repo:  ${name}`)
  if (missing.length === 0 && stale.length === 0) console.log('  they agree')
  process.exit(missing.length + stale.length === 0 ? 0 : 1)
}

/* ---- --briefs: the one source, for anything that needs to agree with it ----- */

/**
 * **Printed rather than imported, which is this repository's existing shape.**
 * `illustrations.built-test.ts` runs `check-illustration-palette.mjs` with
 * `execFileSync` for the same reason: a `.ts` test importing a `.mjs` script
 * needs type plumbing that buys nothing, and a second copy of the list in
 * `src/` is the duplication `#120` is named after. So the briefs stay here and
 * anything that must agree with them asks.
 */
if (process.argv.includes('--briefs')) {
  console.log(
    JSON.stringify(
      {
        cards: Object.fromEntries(
          Object.entries(CARDS).map(([name, card]) => [
            name,
            {
              drawing: card.drawing,
              neutral: card.neutral === true,
              runtime: card.runtime ?? null,
              fellBack: FELL_BACK[name] ?? null,
            },
          ]),
        ),
      },
      null,
      2,
    ),
  )
  process.exit(0)
}

/* ---- The card ------------------------------------------------------------- */

/**
 * The mark, with its baked-in colours put back as literals.
 *
 * Not `inlineMark`: that returns `var(--k-…)`, which is right for a page that
 * carries `theme.css` and wrong for a standalone document. The values come from
 * the same tokens either way — `build-assets.mjs` generated the file from them.
 */
const MARK = readFileSync(at('public/mark.svg'), 'utf8')
  .replace(/<\?xml[^>]*\?>/, '')
  .replace(/role="img"/, 'aria-hidden="true"')

/** A drawing as a data URI, so the document needs no server and no relative path. */
const drawing = (name) =>
  `data:image/png;base64,${readFileSync(at(`assets/repo-card-drawings/${name}.png`)).toString('base64')}`

const escape = (s) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')

/**
 * **1280×640, which is GitHub's own recommended size for this surface** — not
 * `og.png`'s 1200×630, which is the Open Graph ratio and belongs to a different
 * job (`#90`).
 */
const WIDTH = 1280
const HEIGHT = 640

function document_(repository, card) {
  /**
   * **The neutral card makes no claim at all** (`#90`): mark and name, centred,
   * no illustration and no repository name. It is `.github`'s, and it is the
   * fallback for any repository whose card is not ready.
   */
  const neutral = card.neutral === true

  const right = neutral
    ? ''
    : `<div class="art">
         <div class="frame">
           <img src="${drawing(card.drawing)}" alt="" />
           ${card.crest === true ? `<div class="crest">${MARK}</div>` : ''}
           ${card.runtime === undefined ? '' : `<div class="runtime">${escape(card.runtime)}</div>`}
         </div>
       </div>`

  return `<!doctype html>
<meta charset="utf-8" />
<style>
  @font-face {
    font-family: 'JetBrains Mono';
    src: url('fonts/jetbrains-mono-latin-wght-normal.woff2') format('woff2-variations');
    font-weight: 100 800;
  }
  html, body { margin: 0; padding: 0; }
  body {
    width: ${WIDTH}px; height: ${HEIGHT}px; box-sizing: border-box;
    padding: 64px 72px;
    display: grid;
    grid-template-columns: ${neutral ? '1fr' : '1fr 1fr'};
    align-items: ${neutral ? 'center' : 'stretch'};
    justify-items: ${neutral ? 'center' : 'stretch'};
    gap: 48px;
    background: ${k.bg};
    font-family: 'JetBrains Mono', monospace;
    /* The one rule every card shares, so fourteen of them read as a set. */
    border-bottom: 8px solid ${k.accent};
  }

  /* **The existing lockup, unchanged** — mark, then name. \`brand/README.md\` §4:
     one lockup exists and a second arrangement is a second identity. It is the
     site header's and \`og.png\`'s, and this is the third surface it appears on
     rather than a new pairing. */
  .left { display: flex; flex-direction: column; justify-content: space-between; }
  .lockup { display: flex; align-items: center; gap: 20px; }
  .lockup svg { display: block; width: 76px; height: 76px; }
  .lockup span {
    font-size: 28px; font-weight: 600; letter-spacing: 0.14em; color: ${k.text};
  }

  /* The only other text on the card, and it is small on purpose: a reader tells
     the repositories apart by the drawing and confirms it by the name. */
  .name { font-size: 26px; font-weight: 500; color: ${k.faint}; }

  .art { display: flex; align-items: center; justify-content: center; }

  /* **The overlays are positioned against the picture, not against the cell.**
     A percentage of \`.art\` moves whenever the drawing's aspect ratio does, and
     the eight drawings do not share one — so the frame is exactly the rendered
     image and everything inside it is a fraction of that. */
  .frame { position: relative; display: block; max-width: 100%; max-height: 100%; }
  .frame img { display: block; width: 100%; height: auto; }

  /* The crest inside the browser frame, for \`kolonie-website\`'s card. The
     drawing is an empty frame and this is the real mark — §4 forbids redrawing
     it, and a model asked for one produces a third weight of a shape that has
     two. */
  .crest {
    position: absolute; left: 50%; top: 56%;
    width: 26%; transform: translate(-50%, -50%);
  }
  .crest svg { display: block; width: 100%; height: 100%; }

  /* **The fallback \`#90\` wrote**, for a runtime whose mark the Colony cannot
     use — which is all six. See \`FELL_BACK\` in \`repo-card-briefs.mjs\` for what
     each brand page answered. The name sits in the field the shared drawing
     leaves empty, in the template's own monospace.

     The numbers are measured off the runtime drawing rather than guessed: the
     empty square runs from 34% to 79.5% across and 21% to 78% down, so its
     centre is 57% / 49.5%. Google Antigravity is the longest of the six and
     wraps to two lines inside it, which is why the width is the field's rather
     than the text's. */
  .runtime {
    position: absolute; left: 57%; top: 49.5%;
    width: 40%; transform: translate(-50%, -50%);
    text-align: center; font-size: 21px; font-weight: 500;
    line-height: 1.4; letter-spacing: 0.04em; color: ${k.accent};
  }
</style>
<div class="left">
  <div class="lockup">${MARK}<span>KOLONIE AI</span></div>
  ${neutral ? '' : `<div class="name">${escape(repository)}</div>`}
</div>
${right}
`
}

/* ---- Render --------------------------------------------------------------- */

mkdirSync(at('public/repo-cards'), { recursive: true })

// Written inside `public/` so the `@font-face` URL resolves to the file the site
// serves rather than a lookalike installed on this machine, and removed after.
const source = at('public/.repo-card-source.html')

let browser
try {
  const { chromium } = await import('playwright')
  browser = await chromium.launch()
} catch (error) {
  console.log('repo cards left as they are —', error.message.split('\n')[0])
  process.exit(0)
}

const page = await browser.newPage({ viewport: { width: WIDTH, height: HEIGHT } })
const written = []

try {
  for (const [repository, card] of Object.entries(CARDS)) {
    writeFileSync(source, document_(repository, card))
    await page.goto('file://' + source)
    await page.evaluate(() => document.fonts.ready)

    const shot = await page.screenshot({ type: 'png' })

    /**
     * Palettised, like every other picture this repository commits. A flat
     * drawing and two weights of type on one background do not need 24 bits,
     * and GitHub enforces 1 MB on this surface — these land near 20 KB.
     */
    const out = at(`public/repo-cards/${repository}.png`)
    await sharp(shot).png({ palette: true, colours: 32, effort: 10, compressionLevel: 9 }).toFile(out)
    written.push(repository)
  }
} finally {
  await browser.close()
  rmSync(source, { force: true })
}

console.log(`${written.length} cards: ${written.join(', ')}`)
const fell = Object.keys(FELL_BACK)
if (fell.length > 0) console.log(`${fell.length} runtime cards fell back to type: ${fell.join(', ')}`)
